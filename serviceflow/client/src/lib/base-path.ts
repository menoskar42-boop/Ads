// ============================================================================
// مسار الجذر (base path)
//
// Service Flow ممكن تتقدّم من مكانين:
//   ١. نطاق لوحدها            → serviceflow.oscardevs.com/
//   ٢. مسار تحت أوسكار ديفز   → oscardevs.com/serviceflow/
//
// الحالة التانية اتطلبت عشان **الفلوس**: كل نطاق فرعى على oscardevs.com
// بيعدّى على Cloudflare Worker وبياكل من كوتته، والأبكس (oscardevs.com)
// مستثنى من الـWorker — فمسار تحته بيكلّف صفر.
//
// والمشكلة إن التطبيق بيطلب ملفاته بمسارات **مطلقة** (/assets ·/api ·/ws)،
// فلو اتقدّم تحت مسار هيطلبها من جذر الموقع ويرد عليه أوسكار ديفز. الحل إن
// كل حاجة تتحسب من BASE_URL — وVite بيحطه وقت البناء من SF_BASE_PATH.
// ============================================================================

/** مسار الجذر من غير «/» فى الآخر. بيبقى "" لما التطبيق على جذر نطاقه. */
export const BASE: string = String(import.meta.env.BASE_URL || "/").replace(/\/+$/, "");

/** يضيف مسار الجذر لمسار مطلق. بيتجاهل الروابط الخارجية والمسارات المضافة قبل كده. */
export function withBase(p: string): string {
  if (!BASE) return p;
  if (!p.startsWith("/") || p.startsWith("//")) return p;   // خارجى أو بروتوكول-نسبى
  if (p === BASE || p.startsWith(BASE + "/")) return p;      // مضاف قبل كده
  return BASE + p;
}
