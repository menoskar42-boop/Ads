/**
 * هل العملية دي هي اللي مسؤولة عن المهام المجدولة؟
 *
 * التطبيق بقى بيتشغّل في مكانين في نفس الوقت أثناء فترة التجربة: النشر
 * القديم على ريبليت، والنسخة المستضافة جوّه أوسكار ديفز — **والاتنين على
 * نفس قاعدة البيانات**.
 *
 * المؤقتات التلاتة (اللقطة اليومية · طلب البيانات الفنية الناقصة ·
 * التشغيل اليومي وجلب WFM) كلها متحصّنة على مستوى القاعدة
 * (`ON CONFLICT DO NOTHING` · شرط «مش أكتر من مرة كل ٤ ساعات» ·
 * `app_state.auto_batches_last_day`). فالتشغيل مرتين **مش** بيكرّر بيانات.
 *
 * لكن الحصانة دي متكتوبة لعملية واحدة بتعيد التشغيل، مش لعمليتين
 * شغّالين في نفس اللحظة: الاتنين ممكن يقروا «لسه مااتعملش النهارده» قبل
 * ما أي واحد فيهم يكتب. الاحتمال ضعيف والأثر محدود، لكن ده نظام تشغيل
 * في شركة — فالأأمن إن **عملية واحدة بس** تملك المهام دي أثناء التجربة.
 *
 * الافتراضي **شغّال** — النشر القديم مايتغيّرش سلوكه. النسخة المستضافة
 * بتتشغّل بـ`SF_SCHEDULERS=off` لحد ما المالك يتأكد، وبعدين تتقفل على
 * القديم وتتفتح على الجديد.
 */
export function schedulersEnabled(env: NodeJS.ProcessEnv = process.env): boolean {
  const raw = String(env.SF_SCHEDULERS ?? '').trim().toLowerCase();
  if (!raw) return true;                       // مش متظبّط → شغّال زي الأول
  return !['off', 'false', '0', 'no'].includes(raw);
}
