const SUPPORTED = ['ar', 'en'];
const DEFAULT_LANG = 'ar';

function normalizeLang(input) {
  if (!input) return DEFAULT_LANG;
  const lower = String(input).toLowerCase().slice(0, 2);
  return SUPPORTED.includes(lower) ? lower : DEFAULT_LANG;
}

function t(key, lang) {
  const l = normalizeLang(lang);
  if (strings[l] && strings[l][key]) return strings[l][key];
  if (strings.en && strings.en[key]) return strings.en[key];
  return key;
}

// Picks the appropriate localized field from a row depending on company's
// content_i18n flag and current visitor language.
//   row: any row that may have name / name_ar / name_en, etc.
//   baseField: e.g. 'name', 'description'
//   lang: 'ar' | 'en'
//   companyContentI18n: boolean
function pickContent(row, baseField, lang, companyContentI18n) {
  if (!row) return '';
  if (!companyContentI18n) return row[baseField] || '';
  const l = normalizeLang(lang);
  const localized = row[baseField + '_' + l];
  if (localized) return localized;
  const other = row[baseField + '_' + (l === 'ar' ? 'en' : 'ar')];
  return localized || other || row[baseField] || '';
}

module.exports = { t, normalizeLang, pickContent, SUPPORTED, DEFAULT_LANG, strings };
