// كام كلمة كتبها التاجر فعلاً.
//
// بوابات الفهرسة في `routes/tenant.js` بتقيس بطول **الحروف** (`description`
// أطول من ٤٠ حرف). أربعين حرف عربي = ست كلمات تقريباً، وصفحة بست كلمات
// بتعدّي البوابة وبتتأرشف — وهي أقل من حد المشروع نفسه (١٢٠ كلمة) اللي
// `seo-audit` بيرفض تحته.
//
// والفرق مش شكلي: صفحة رقيقة بتتأرشف = صفحة doorway محتملة ضد حساب أدسنس،
// وده الخط الأحمر المكتوب في `CLAUDE.md`.
//
// الدالة دي بتعدّ **كلام التاجر نفسه** (نبذته، خدماته…) — مش كلامنا إحنا
// اللي في القالب، لأن ده بيظهر لكل صفحة وماينفعش يبقى سبب لأرشفة صفحة فاضية.
'use strict';

/** كلمات النص، عربي أو إنجليزي. الفاضي صفر — مش «مش معروف». */
function words(text) {
  const s = String(text == null ? '' : text).trim();
  if (!s) return 0;
  return s.split(/\s+/).filter(Boolean).length;
}

/** مجموع كلمات كذا حقل. `null` بتتعدّ صفر لأنها فعلاً مافيهاش كلام. */
function totalWords(parts) {
  return (parts || []).reduce((n, p) => n + words(p), 0);
}

/**
 * هل الصفحة تستاهل تتأرشف؟
 *
 * @param texts   نصوص التاجر (نبذة، خدمات، وصف…)
 * @param rows    عدد الصفوف الحقيقية (منتجات، أطباء، باقات…) — كل صف بيوزن
 *                كلمات لأنه سطر محتوى حقيقي على الصفحة
 * @param min     الحد الأدنى بالكلمات (٤٠ افتراضياً = مع كلام القالب بتعدّي
 *                حد الـ١٢٠ كلمة اللي الفحص بيقيس بيه)
 *
 * بيرجع `{ ok, count }` — والعدد بيتعرض في اللوج عشان التاجر/المطوّر يعرف
 * فاضل كام، مش «لأ» من غير سبب.
 */
function enough(texts, rows, min) {
  const limit = Number.isFinite(min) ? min : 40;
  const perRow = 6;   // سطر منتج/طبيب/باقة ≈ اسم ووصف قصير
  const count = totalWords(texts) + Math.max(0, Number(rows) || 0) * perRow;
  return { ok: count >= limit, count, min: limit };
}

module.exports = { words, totalWords, enough };
