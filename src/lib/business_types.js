'use strict';
/**
 * أنواع النشاط الاتناشر — تعريف واحد، والباقي بيقرا منه.
 *
 * ── المشكلة اللي اتكشفت في مراجعة الكود الخارجية ───────────────────────
 *
 * التصنيف كان متكتوب **تلات مرات** بتلات مستويات اكتمال:
 *
 *   · `apply.js`  — سلسلة كاملة بالاتناشر نوع ✅
 *   · `admin.js`  — تلاتة بس، وأي حاجة تانية → «بورتفوليو» ❌
 *   · قوالب الأدمن — واحد بس (`shop`)، وأي حاجة تانية → «بورتفوليو» ❌
 *
 * النتيجة إن طلب عيادة أو جيم أو ورشة بيتعرض في لوحة الأدمن وبيتسجّل في
 * CRM على إنه **بورتفوليو**. مافيش خطأ، مافيش لوج — بس التقارير بتكدب،
 * والبايع بيفتح الـlead ويكلّم صاحب عيادة عن موقع بورتفوليو.
 *
 * وده مش احتمال نظري: تسعة من اتناشر نوع كانوا واقعين في الحالة دي.
 *
 * ── ليه ملف لوحده ──────────────────────────────────────────────────────
 *
 * `apply.js` كان صح. المشكلة مش إن حد كتب غلط — المشكلة إن فيه **تلات
 * نسخ**، واللي بيضيف نوع تلتاشر لازم يفتكر تلات أماكن. النسخة الواحدة
 * بتخلّي النسيان مستحيل بدل ما تخلّيه غلطة.
 *
 * ⚠️ الترتيب هنا هو ترتيب `BUSINESS_TYPES` في `apply.js`، و
 * `check-page-types` بيتأكد إن الاتنين متطابقين.
 */

/**
 * لكل نوع: اسمه للأدمن، وتصنيفه في CRM.
 *
 * `label` بيتعرض في لوحة الأدمن، و`crm` بيتخزّن في `crm_leads.category`.
 * الاتنين مختلفين عن قصد: الأدمن عايز اسم قصير، وCRM عايز تصنيف بيتجمّع
 * عليه في التقارير.
 */
const TYPES = {
  shop:         { label: 'متجر إلكتروني',        crm: 'متجر' },
  portfolio:    { label: 'بورتفوليو',            crm: 'بورتفوليو' },
  pharmacy:     { label: 'صيدلية',               crm: 'صيدلية' },
  orders:       { label: 'مطعم وطلبات',          crm: 'مطاعم/طلبات' },
  clinic:       { label: 'عيادة',                crm: 'عيادة' },
  gym:          { label: 'جيم',                  crm: 'جيم/لياقة' },
  furniture:    { label: 'معرض موبيليا',         crm: 'موبيليا/ورشة' },
  nutrition:    { label: 'عيادة تغذية',          crm: 'تغذية علاجية' },
  workshop:     { label: 'ورشة سيارات',          crm: 'ورش سيارات' },
  hall:         { label: 'قاعة أفراح',           crm: 'قاعات أفراح' },
  nursery:      { label: 'حضانة ومركز دروس',     crm: 'حضانات/مراكز دروس' },
  installments: { label: 'بيع بالتقسيط',         crm: 'بيع بالتقسيط' },
};

/** المفاتيح بالترتيب — دي القايمة اللي `apply.js` بيتحقّق منها. */
const KEYS = Object.keys(TYPES);

/**
 * اسم النوع للعرض.
 *
 * ⚠️ النوع المش معروف بيرجّع **النص نفسه** مش «بورتفوليو». الرجوع
 * لبورتفوليو هو بالظبط الغلطة اللي الملف ده اتعمل عشانها: بيخفي المشكلة
 * بدل ما يوريها. لو ظهر نوع غريب في الشاشة، ده معناه إن فيه نوع اتضاف من
 * غير ما يتسجّل هنا — وده اللي عايزين نشوفه.
 */
function labelOf(type) {
  const t = TYPES[type];
  return t ? t.label : String(type || 'غير محدّد');
}

/** تصنيف CRM. نفس القاعدة: المش معروف مابيتحوّلش لبورتفوليو. */
function crmCategoryOf(type) {
  const t = TYPES[type];
  return t ? t.crm : String(type || 'غير محدّد');
}

module.exports = { TYPES, KEYS, labelOf, crmCategoryOf };
