/** A short label for the "other systems" strip, derived from the title. */
function label(entry) {
  return entry.title.split('—')[0].replace(/^(برنامج|نظام)\s+/, '').trim();
}

/** The list every page links to, minus itself — internal links a crawler
 *  can walk, and the reason none of these pages is an orphan. */
function othersOf(slug) {
  return Object.keys(SECTORS).filter((k) => k !== slug)
    .map((k) => ({ slug: k, label: label(SECTORS[k]) }));
}

module.exports = { SECTORS, othersOf, label };
