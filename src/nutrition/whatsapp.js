// رقم العميل بالشكل اللي wa.me بيفهمه — للزرار «ابعت على واتساب».
//
// wa.me عايز الرقم دولي أرقام بس: من غير + ولا 00 ولا مسافات ولا الصفر
// المحلي. «01012345678» على wa.me بيفتح شات رقم مش موجود — والأخصائي بيبعت
// خطة مريض لحد تاني لو الرقم اتفهم غلط. فاللي مش واضح بيرجع null، والزرار
// بيفتح واتساب يختار منه جهة الاتصال بنفسه بدل ما نخمّن.
'use strict';

const AR_DIGITS = '٠١٢٣٤٥٦٧٨٩';

function waPhone(raw) {
  let d = String(raw || '')
    .replace(/[٠-٩]/g, (c) => String(AR_DIGITS.indexOf(c)))
    .replace(/\D/g, '');
  if (!d) return null;
  if (d.startsWith('00')) d = d.slice(2);
  // موبايل مصري محلي: 01xxxxxxxxx (١١ رقم) → 201xxxxxxxxx
  if (/^01[0125]\d{8}$/.test(d)) return '2' + d;
  // ودولي مصري مكتوب من غير الـ+: 201xxxxxxxxx
  if (/^201[0125]\d{8}$/.test(d)) return d;
  // أي رقم دولي تاني (الخليج مثلاً) لازم يكون مكتوب بكود البلد: ١٠–١٥ رقم
  // ومايبدأش بصفر. المحلي من غير كود مانقدرش نعرف بلده.
  if (/^[1-9]\d{9,14}$/.test(d) && !/^1[0125]\d{8}$/.test(d)) return d;
  return null;
}

module.exports = { waPhone };
