#!/usr/bin/env node
/**
 * خدمات التطوير المخصّص **مش** أنظمة جاهزة — والفرق ده لازم يفضل مكتوب.
 *
 * ── الغلطة اللي الفحص ده بيمنعها ───────────────────────────────────────
 *
 * `SYSTEMS_COUNT` في `company_facts.js` محسوب من `Object.keys(PRICES).length`،
 * والرقم ده بيتقال في الرئيسية وصفحة الحقائق و`llms.txt`. لو حد ضاف خدمة
 * التطوير المخصّص في `pricing.js` (وده تصرّف طبيعي — «هي كمان بتتباع، يبقى
 * سعرها هناك»)، العدد كان هيقفز لـ١٥ في تلات أماكن مرة واحدة، ومحرّك
 * الإجابة كان هيقول «عندهم ١٥ نظام جاهز».
 *
 * ودي بالظبط نفس عيلة الغلطة اللي اتصلّحت قبل كده في `llms.txt` («اتناشر
 * ولا تلتاشر؟» بسبب صفحة الأسنان). الغموض في تعريف الكيان هو اللي خلّى
 * قياس الجيو يطلّع **صفر ذكر** لـOscarDevs — مكتوب في `docs/GEO_BASELINE.md`.
 *
 * ── والتسعير ───────────────────────────────────────────────────────────
 *
 * الأنظمة الجاهزة ليها سعر ثابت. المشروع المخصّص مالوش — سعره نتيجة نطاقه.
 * فممنوع رقم سعر في صفحة خدمة، وممنوع `offers` في سكيمتها. `offers` بسعر
 * مخترع هي غلطة السكيمة رقم ٩ في `docs/SEO_MISTAKES_LOG.md`.
 *
 * Usage: node scripts/check-services.js
 */
'use strict';
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');
const read = (p) => fs.readFileSync(path.join(ROOT, p), 'utf8');

let failed = 0;
const check = (label, ok, why) => {
  console.log((ok ? '✅ ' : '❌ ') + label + (ok ? '' : '\n   ' + why));
  if (!ok) failed += 1;
};

/**
 * شيل التعليقات قبل أي بحث عن نص ممنوع.
 *
 * التعليق اللي بيشرح **ليه** الحاجة ممنوعة مالوش ذنب — ولو الفحص شافه
 * وفشل، أول حل هيخطر على بال اللي بيصلّح هو إنه يمسح الشرح. ودي غلطة
 * اتعملت في المشروع ده **أربع مرات**.
 */
const code = (s) => s
  .replace(/<%#[\s\S]*?%>/g, ' ')
  .replace(/\/\*[\s\S]*?\*\//g, ' ')
  .replace(/^\s*\/\/.*$/gm, ' ');

const { SERVICES } = require('../src/lib/services');
const { PRICES } = require('../src/lib/pricing');
const names = Object.keys(SERVICES);

// ── ١) الخدمة مش في جدول أسعار الأنظمة ─────────────────────────────────

const keys = names.map((s) => SERVICES[s].key);
const leaked = keys.filter((k) => Object.prototype.hasOwnProperty.call(PRICES, k));
check('خدمات التطوير بره `PRICES` — فعدد الأنظمة الجاهزة ما اتغيّرش',
  leaked.length === 0,
  `«${leaked.join('، ')}» في PRICES — وده بيزوّد SYSTEMS_COUNT في الرئيسية `
  + 'وصفحة الحقائق و`llms.txt` مرة واحدة. الخدمة مالهاش سعر ثابت أصلاً.');

check('عدد الأنظمة الجاهزة لسه ١٢', Object.keys(PRICES).length === 12,
  `بقى ${Object.keys(PRICES).length}. لو ده مقصود (نظام جديد اتضاف فعلاً)، `
  + 'غيّر الرقم هنا. لو مش مقصود، يبقى خدمة اتحطّت في `PRICES`.');

// ── ٢) مفيش سعر مكتوب في صفحة خدمة ─────────────────────────────────────

const viewSrc = code(read('src/views/landing/service.ejs'));
const libSrc = code(read('src/lib/services.js'));
// رقم متبوع بـ«ج» أو «جنيه» أو EGP = ادعاء سعر.
//
// ⚠️ `ج\b` **مابيشتغلش**: الـ`\b` في جافاسكريبت حدّ كلمة **ASCII**، و«ج»
// مش حرف ASCII — فمفيش حدّ بينها وبين النقطة اللي بعدها، والتعبير كان
// بيعدّي على «١٥٬٠٠٠ ج.» من غير ما يمسكها. الصح هو نظرة أمامية بتقول
// إن اللي بعد الجيم مش حرف عربي (عشان مانمسكش «جديد» مثلاً).
const PRICE_RE = /[\d٠-٩][\d٠-٩٬,.]*\s*(?:جنيه|EGP|ر\.س|درهم|\$|ج(?![\u0621-\u064A]))/;
for (const [label, src] of [['القالب', viewSrc], ['ملف الخدمات', libSrc]]) {
  const hit = PRICE_RE.exec(src);
  check(`مفيش رقم سعر في ${label}`, !hit,
    hit ? `لقيت «${hit[0].trim()}». سعر المشروع المخصّص نتيجة نطاقه — `
      + 'ورقم على الصفحة بيتحوّل لتوقّع بيتكسر بعد ما العميل يكون بدأ.' : '');
}

// ── ٣) مفيش `offers` في سكيمة الخدمة ───────────────────────────────────

check('مفيش `offers` في سكيمة صفحة الخدمة', !/"offers"/.test(viewSrc),
  '`offers` من غير سعر حقيقي هو ادعاء سعر في البيانات المنظّمة — '
  + 'غلطة السكيمة رقم ٩ في `docs/SEO_MISTAKES_LOG.md`.');

// ── ٤) كل خدمة ليها route وفي السايت‌ماب ────────────────────────────────

const legal = read('src/routes/legal.js');
check('الخدمات متسجّلة كـroutes', /Object\.keys\(SERVICES\)[\s\S]{0,200}router\.get\('\/' \+ slug/.test(legal),
  'مافيش حلقة بتسجّل صفحات الخدمات في `src/routes/legal.js`.');
check('الخدمات في السايت‌ماب',
  /Object\.keys\(SERVICES\)\.map\(\(slug\) => \(\{ loc: '\/' \+ slug/.test(legal),
  'صفحة مفهرسة مش في السايت‌ماب = محدش بيوصّل الزواحف لها. ده كان بالظبط '
  + 'اللي حصل مع صفحة ورش السيارات.');

// ── ٥) `llms.txt` بيفرّق بين الخدمة والنظام ─────────────────────────────
//
// ده جوهر الفحص. القايمة لوحدها مش كفاية — لازم جملة صريحة تقول إن
// التلاتة دول مش بيتضافوا على الاتناشر.

const llms = legal.slice(legal.indexOf("router.get('/llms.txt'"));
check('`llms.txt` فيه قسم خدمات منفصل', /خدمات التطوير المخصّص/.test(llms),
  'الخدمات مش مذكورة في `llms.txt` خالص.');
check('و`llms.txt` بيقول صراحةً إنها خدمات مش أنظمة',
  /توضيح للعدّ[\s\S]{0,400}خدمات تطوير[\s\S]{0,400}مش أنظمة جاهزة/.test(llms)
  || /خدمات تطوير\*\*، مش أنظمة جاهزة/.test(llms),
  'من غير الجملة دي، اللي بيقرا الملف بيجمع ٣ + ١٢ ويقول ١٥ نظام. '
  + 'نفس مشكلة «١٢ ولا ١٣» اللي اتصلّحت قبل كده بسبب صفحة الأسنان.');

// ── ٦) وكل صفحة خدمة بتقول بنفسها إن الأنظمة الجاهزة موجودة وأرخص ───────
//
// الصفحة اللي بتبيع تطوير مخصّص لحد نشاطه صيدلية هي صفحة بتضيّع فلوس
// العميل ووقتنا. القالب بيقول ده، والفحص بيتأكد إنه لسه بيقوله.

check('صفحة الخدمة بتوجّه اللي نشاطه ليه نظام جاهز',
  /نظام جاهز/.test(viewSrc) && /readySystemsAr/.test(viewSrc),
  'القالب مابيقولش للزائر إن فيه أنظمة جاهزة أرخص وأسرع لو نشاطه منها.');

// ── ٧) وكل خدمة عندها المحتوى اللي القالب بيتوقّعه ──────────────────────

for (const slug of names) {
  const v = SERVICES[slug];
  const missing = ['title', 'desc', 'h1', 'lead', 'forWho', 'pains', 'features', 'steps', 'faq', 'serviceType']
    .filter((f) => !v[f] || (Array.isArray(v[f]) && !v[f].length));
  check(`[${slug}] الحقول مكتملة`, missing.length === 0, `ناقص: ${missing.join('، ')}`);
  // حدود Bing من `docs/BING_WEBMASTER_HELP.md`.
  check(`[${slug}] العنوان ≤٦٠ والوصف ١٥٠–١٦٠`,
    v.title.length <= 60 && v.desc.length >= 150 && v.desc.length <= 160,
    `العنوان ${v.title.length} · الوصف ${v.desc.length}`);
}

process.exit(failed ? 1 : 0);
