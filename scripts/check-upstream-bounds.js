#!/usr/bin/env node
/**
 * حاجتين بيوقّفوا سيرفر من غير ما يكسروه: انتظار بلا مهلة، ومدخل بلا حد.
 *
 * ── ١) بوّابة الاستضافة كانت بتستنى للأبد ────────────────────────────────
 *
 * `host_gateway` بيمرّر الطلب لتطبيق مستضاف تاني. الطلب مكنش له `timeout`،
 * يعني لو التطبيق ده **علّق** (مش وقع — علّق)، الاتصال بيفضل مفتوح: العميل
 * مستني، والاتصال محجوز عندنا، والاتصالات دي بتتراكم لحد ما السيرفر مايقدرش
 * يستقبل. الوقوع كان له علاج (`error`)؛ التعليق مكنش.
 *
 * ولاحظ حاجة سهل تتنسى: `timeout` في Node **بتطلق الحدث بس مابتقفلش
 * الاتصال**. القفل لازم يتعمل بالإيد، وإلا الاتصال بيفضل محجوز واحنا فاكرين
 * إننا خلاص منه.
 *
 * ── ٢) وريجيكس المخطّط كان بيشتغل على مدخل بلا حد ───────────────────────
 *
 * مراجعة خارجية قالت إن الريجيكس ده «ReDoS» بتراجع كارثي. **اتقاس فعلاً**
 * قبل ما يتغيّر أي حاجة: النقطة فاصل صريح فمافيش انفجار أسّي — الزمن تربيعي
 * لا أكتر (٥ آلاف مقطع ≈ ٨٠ مللي، ٢٠ ألف ≈ ١٫٥ ثانية). فالعلاج مش إعادة
 * كتابة الريجيكس وكأنه متفجّر — ده إن **المدخل يتحدّد**. الهدف اللي طوله
 * أكتر من ٢ كيلو مش هدف أصلاً.
 *
 *   node scripts/check-upstream-bounds.js
 */
'use strict';
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');

let fail = 0;
const check = (label, ok, extra) => {
  console.log((ok ? '✅ ' : '❌ ') + label + (extra !== undefined ? ' — ' + extra : ''));
  if (!ok) fail++;
};
const nl = (m) => m.replace(/[^\n]/g, ' ');
const code = (rel) => fs.readFileSync(path.join(ROOT, rel), 'utf8')
  .replace(/\/\*[\s\S]*?\*\//g, nl)
  .replace(/(^|[^:])\/\/[^\n]*/g, (m, p) => p + nl(m.slice(p.length)));

/* ── ١. بوّابة الاستضافة ──────────────────────────────────────────────── */
{
  const g = code('src/lib/host_gateway.js');
  check('الطلب للتطبيق المستضاف له مهلة',
    /timeout: UPSTREAM_TIMEOUT_MS/.test(g) && /const UPSTREAM_TIMEOUT_MS = \d+/.test(g));
  check('والمهلة معقولة (مش ثانية ولا ساعة)',
    /const UPSTREAM_TIMEOUT_MS = (\d+)/.test(g)
    && Number(RegExp.$1) >= 5000 && Number(RegExp.$1) <= 120000, RegExp.$1 + 'ms');
  check('والاتصال بيتقفل بالإيد لما المهلة تعدّي (الحدث لوحده مابيقفلش)',
    /on\('timeout', \(\) => \{ upstream\.destroy\(/.test(g));
  check('والوقوع لسه بيرد ٥٠٢ بجملة مفهومة',
    /on\('error'[\s\S]{0,200}502/.test(g));
  check('والعميل اللي مشي مابيسيبناش شادّين على اتصال فوق',
    /res\.on\('close'[\s\S]{0,120}upstream\.destroy\(\)/.test(g));
}

/* ── ٢. حد المدخل في المخطّط ───────────────────────────────────────────── */
{
  const p = code('sokro/ai/planner.js');
  check('الهدف بيتقصّ قبل الريجيكس', /String\(goal\)\.slice\(0, \d+\)\.match\(domainRe\)/.test(p));

  // مقيس مش مفترض: الحد بيخلّي أسوأ مدخل يعدّي في وقت مهمل.
  const re = /\b((?:[a-z0-9-]+\.)+(?:com|net|org|io|eg|co|me|app|store|shop|dev|ai|gov|edu|sa|ae)(?:\.[a-z]{2})?)(\/[^\s]*)?/i;
  const worst = 'ab.'.repeat(50000).slice(0, 2000);
  const t0 = Date.now(); re.test(worst); const ms = Date.now() - t0;
  check('وأسوأ مدخل بعد القص بياخد وقت مهمل', ms < 50, ms + 'ms');
}

/* ── ٣. تنظيف المسار بيفكّ الترميز مرة واحدة ───────────────────────────── */
{
  // مراجعة خارجية قالت إن `req.path` بيوصل مفكوك خلاص من إكسبريس، وإن
  // السطر ده بيفكّه تاني. **اتجرّب**: إكسبريس بيسيبه مرمّز زي ما جه
  // (`/apply%D8%8C` بتوصل كما هي)، فالفكّة دي هي الأولى مش التانية — وشيلها
  // كان هيكسّر الحاجة اللي الميدل‌وير موجود عشانها أصلاً (الفاصلة العربية
  // الملزوقة في آخر اللينك).
  const s = code('server.js');
  const decodes = (s.match(/decodeURIComponent\(req\.path\)/g) || []).length;
  check('المسار بيتفك مرة واحدة بالظبط', decodes === 1, decodes + ' مرة');
  check('والمكسور بيعدّي بدل ما يوقع الطلب',
    /catch \(e\) \{ return next\(\); \}/.test(s));
  check('وبيترمّز تاني قبل التحويل',
    /cleaned\.split\('\/'\)\.map\(encodeURIComponent\)\.join\('\/'\)/.test(s));
}

console.log(fail === 0
  ? '\n✅ مفيش انتظار بلا مهلة، ولا مدخل بلا حد.'
  : `\n⚠️  ${fail} مشكلة.`);
process.exit(fail === 0 ? 0 : 1);
