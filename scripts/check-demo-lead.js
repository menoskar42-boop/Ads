#!/usr/bin/env node
/**
 * الديمو بيلتقط عميل — من غير ما يقفل الديمو.
 *
 * ── البند ───────────────────────────────────────────────────────────────
 *
 * أعلى بند إيراد في التقرير الموحّد: `/demo/<slug>` بيدخّل الزائر لوحة
 * التحكم على طول، فبيلف ويجرّب ويمشي و**محدّش يعرف إنه جه**.
 *
 * ── والقرار اللي الفحص بيحرسه ───────────────────────────────────────────
 *
 * الحل السهل فورم **قبل** الديمو. مرفوض: الديمو شغلته يقنع، وبوابة قبله
 * بتصفّي اللي لسه مش مقتنع — يعني بتفقد بالظبط اللي الديمو اتعمل عشانه.
 *
 * فالفحص ده بيحرس حاجتين ضد بعض:
 *   ١) إن فيه التقاط أصلاً.
 *   ٢) وإنه **مايقفلش الديمو** — `/demo/:slug` يفضل بيدخّل على طول.
 *
 * وفيه تالتة بتفرق في المبيعات: الـlead لازم يشيل **أنهي ديمو اتجرّب**.
 * من غيرها بيبقى «حد مهتم»، ومعاها «حد جرّب نظام الصيدلية».
 *
 *   node scripts/check-demo-lead.js
 */
'use strict';
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');

let fail = 0;
const check = (label, ok, extra) => {
  console.log((ok ? '✅ ' : '❌ ') + label + (extra !== undefined ? ' — ' + extra : ''));
  if (!ok) fail++;
};
const raw = (rel) => fs.readFileSync(path.join(ROOT, rel), 'utf8');
const code = (rel) => raw(rel).replace(/\/\*[\s\S]*?\*\//g, ' ')
  .replace(/(^|[^:])\/\/[^\n]*/g, '$1 ');

const server = code('server.js');
// `code()` مش `raw()` للقالب كمان: التعليقات اللي بتشرح **ليه** اتجنّبنا
// «خلال ساعة» و`localStorage` بتذكرهم بالضرورة. الفحص يقرا الكود المنفَّذ.
// (المصيدة دي وقعت فيها أربع مرات في الفحوص — التعليق مش سلوك.)
const layout = code('src/views/company/_layout_top.ejs')
  .replace(/<%#[\s\S]*?%>/g, ' ');
const M = require('../src/lib/demo_lead');

/* ── ١. الديمو لسه مفتوح ──────────────────────────────────────────────── */
{
  // الشرط الأهم: راوت الديمو بيدخّل على طول، مافيش فورم قبله.
  const route = (server.match(/app\.get\('\/demo\/:slug'[\s\S]*?\n\}\);/) || [''])[0];
  check('/demo/:slug لسه بيدخّل على طول (مافيش بوابة)',
    /res\.redirect\('\/company\/dashboard'\)/.test(route)
    && !/render\([^)]*lead/i.test(route),
    'بوابة قبل الديمو بتصفّي اللي لسه مش مقتنع');

  check('والفورم جوّه شريط الديمو مش قبله',
    /id="demoLead"/.test(layout) && /session\.demoReadOnly/.test(layout));
}

/* ── ٢. الـlead بيشيل أنهي ديمو اتجرّب ───────────────────────────────── */
{
  const r = M.leadFrom({ name: 'أحمد', phone: '01012345678' }, 'pharmacy');
  check('الـlead بيشيل سلَج الديمو في `category` و`source`',
    r.ok && r.lead.category === 'pharmacy' && r.lead.source === 'demo:pharmacy',
    r.ok ? r.lead.source : r.error);
}

/* ── ٣. مايتسجّلش تحت اسم عميل حقيقي ─────────────────────────────────── */
{
  // السلَج بييجي من الجلسة، بس لو حد لعب فيه الـlead كان هيتنسب لعميل
  // حقيقي في لوحة الـCRM.
  const r = M.leadFrom({ name: 'أحمد', phone: '01012345678' }, 'hand');
  check('وسلَج مش تجريبي مابيتسجّلش',
    r.ok && r.lead.category === null && r.lead.source === 'demo',
    'أي سلَج بره قايمة الديمو = عميل حقيقي');
}

/* ── ٤. الرقم بيتخزّن بشكل يتبعت منه واتساب ──────────────────────────── */
{
  // الزائر بيكتب بلوحة مفاتيح عربية. رقم متخزّن «٠١٠…» مايتبعتش منه
  // واتساب ولا بيتلاقى بالبحث.
  const cases = [
    ['٠١٠١٢٣٤٥٦٧٨', '01012345678', 'أرقام عربية'],
    ['+201012345678', '01012345678', 'بكود الدولة'],
    ['0101 234 5678', '01012345678', 'بمسافات'],
    ['123', null, 'قصير'],
    ['', null, 'فاضي'],
  ];
  const wrong = cases.filter(([i, want]) => M.normalizePhone(i) !== want);
  check('الرقم بيتوحّد قبل الحفظ',
    wrong.length === 0, wrong.map((c) => c[2]).join(' · ') || cases.length + ' حالة');
}

/* ── ٥. الراوت مقفول ومابيكدبش ───────────────────────────────────────── */
{
  const route = (server.match(/app\.post\('\/demo\/lead'[\s\S]*?\n\}\);/) || [''])[0];
  check('الراوت مقفول على جلسة ديمو حقيقية',
    /req\.session\.demoReadOnly\) return res\.status\(403\)/.test(route),
    'من غيره فورم مفتوح يحشي جدول العملاء');

  // التكرار بيتمنع جوّه جملة الإدخال — قراءة ثم كتابة بيسيبوا فتحة
  // لطلبين في نفس اللحظة.
  check('والتكرار بيتمنع جوّه جملة الإدخال',
    /WHERE NOT EXISTS \(SELECT 1 FROM crm_leads WHERE phone = \$2\)/.test(route));

  // الفشل بيتقال. «تم» على إدخال فشل بيخلّي الزائر يستنى مكالمة مش جاية.
  check('وفشل الحفظ بيرجع خطأ مش نجاح',
    /status\(500\)\.json\(\{ ok: false/.test(route),
    '«تم» على فشل = الزائر بيستنى مكالمة مش جاية');
}

/* ── ٦. مافيش وعد بميعاد ──────────────────────────────────────────────── */
{
  // رسالة النجاح بتقول «هنكلّمك» — مش «خلال ساعة». الوعد بميعاد محدّش
  // ضامنه بيتحوّل لشكوى.
  const promises = ['خلال ساعة', 'خلال ساعتين', 'خلال ٢٤', 'خلال 24', 'فوراً'];
  const found = promises.filter((p) => layout.includes(p));
  check('رسالة النجاح مافيهاش وعد بميعاد', found.length === 0, found.join(', ') || 'نضيفة');

  check('و«مش دلوقتي» بتفضل للجلسة بس',
    /sessionStorage/.test(layout) && !/localStorage/.test(layout),
    'localStorage معناها الزائر مايشوفوش تاني أبداً');
}

console.log(fail ? `\n⚠️  ${fail} مخالفة.` : '\nالديمو بيلتقط عميل وهو لسه مفتوح.');
process.exit(fail ? 1 : 0);
