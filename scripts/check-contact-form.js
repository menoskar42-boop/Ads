#!/usr/bin/env node
/**
 * نموذج التواصل بيرفض الإيميل والتليفون الغلط — وبيطلب وسيلة رد.
 *
 * ── الغلطة اللي اتصلّحت ────────────────────────────────────────────────
 *
 * الشرط كان `!name || !message` بس. يعني:
 *
 *     email = "not-an-email"   phone = "abc"   →  ✅ تم الإرسال بنجاح
 *
 * مسكها فحص QA خارجي (`BUG-FORM-005`). والضرر مش شكلي: العميل اللي يغلط
 * في رقمه — حرف ناقص، لوحة مفاتيح عربية — بيشوف رسالة نجاح ويستنّى رد
 * **عمره ما هييجي**، وإحنا فاكرين إننا استلمنا رسالته. عميل ضاع وإحنا
 * مش عارفين إنه ضاع.
 *
 * وكان ينفع كمان تتبعت رسالة **من غير إيميل ولا تليفون خالص** — رسالة
 * مالهاش وسيلة رد.
 *
 * ── ⚠️ والقاعدة اللي سهل تتكسر ─────────────────────────────────────────
 *
 * فيه دالة تانية اسمها `normalizePhone` في `src/lib/demo_lead.js`، وهي
 * **بتفرض رقم مصري** (`01` وأحد عشر رقم). ده صح هناك — الديمو للسوق
 * المصري. لكن نموذج التواصل بيوصله أرقام خليجية بعد ما فتحنا السعودية
 * والإمارات، ولو حد «وحّد» الاتنين هيقفل الباب على السوق الجديد من غير
 * ما يلاحظ. الفحص بيتأكد إن الرقم السعودي بيعدّي هنا.
 *
 * Usage: node scripts/check-contact-form.js
 */
'use strict';
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');
const read = (p) => fs.readFileSync(path.join(ROOT, p), 'utf8');

let failed = 0;
const check = (label, ok, why) => {
  console.log((ok ? '✅ ' : '❌ ') + label + (ok ? '' : '\n   ' + why));
  if (!ok) failed += 1;
};

const cv = require('../src/lib/contact_validate');
const base = { name: 'أحمد', message: 'عايز نظام للصيدلية' };

// ── ١) الحالات اللي كانت بتعدّي وهي غلط ────────────────────────────────

const REJECT = [
  [{ ...base, email: 'not-an-email' }, 'email', 'الإيميل اللي فحص الـQA بعته'],
  [{ ...base, email: 'ahmed@' }, 'email', 'إيميل ناقص نطاق'],
  [{ ...base, email: '@gmail.com' }, 'email', 'إيميل بلا اسم'],
  [{ ...base, email: 'ahmed@gmail' }, 'email', 'بلا امتداد'],
  [{ ...base, email: 'a b@c.com' }, 'email', 'فيه مسافة'],
  [{ ...base, phone: 'abc' }, 'phone', 'التليفون اللي فحص الـQA بعته'],
  [{ ...base, phone: '123' }, 'phone', 'رقم قصير'],
  [{ ...base, phone: '1234567890123456789' }, 'phone', 'رقم طويل'],
  [base, 'contact', 'مفيش وسيلة رد خالص'],
  [{ message: 'x', email: 'a@b.com' }, 'name', 'بلا اسم'],
  [{ name: 'أحمد', email: 'a@b.com' }, 'message', 'بلا رسالة'],
];
for (const [body, field, label] of REJECT) {
  const r = cv.validate(body);
  check(`مرفوض: ${label}`, !r.ok && r.field === field,
    r.ok ? 'عدّى وهو غلط!' : `اترفض بسبب «${r.field}» والمتوقّع «${field}»`);
  if (!r.ok) {
    check(`  ورسالته بالعربي`, /[ء-ي]/.test(r.error || ''),
      `الرسالة «${r.error}» — الزائر بيقراها زي ما هي.`);
  }
}

// ── ٢) والحالات اللي **لازم** تعدّي ────────────────────────────────────

const ACCEPT = [
  [{ ...base, email: 'ahmed@gmail.com' }, 'إيميل عادي'],
  [{ ...base, phone: '01552406406' }, 'موبايل مصري'],
  [{ ...base, phone: '٠١٥٥٢٤٠٦٤٠٦' }, 'موبايل مصري بأرقام عربية'],
  [{ ...base, phone: '+966512345678' }, 'موبايل سعودي'],
  [{ ...base, phone: '+971501234567' }, 'موبايل إماراتي'],
  [{ ...base, phone: '0882123456' }, 'أرضي أسيوط'],
  [{ ...base, email: 'a@b.co.uk', phone: '+201552406406' }, 'الاتنين'],
];
for (const [body, label] of ACCEPT) {
  const r = cv.validate(body);
  check(`مقبول: ${label}`, r.ok, r.ok ? '' : `اترفض: ${r.field} — ${r.error}`);
}

// ── ٣) الأرقام العربية بتتحوّل ─────────────────────────────────────────
//
// رقم متخزّن بأرقام عربية مايتبعتش منه واتساب — وده أول حاجة بنعملها
// مع أي lead.

check('الرقم العربي بيتخزّن بأرقام إنجليزية',
  cv.validate({ ...base, phone: '٠١٥٥٢٤٠٦٤٠٦' }).value.phone === '01552406406',
  'لو اتخزّن عربي، مافيش واتساب هيتبعت منه.');

// ── ٤) والسوق الخليجي مش مقفول ─────────────────────────────────────────
//
// القاعدة اللي أسهل حاجة تتكسر: `demo_lead.normalizePhone` بيفرض رقم
// مصري، ولو حد وحّد الاتنين هيقفل السعودية والإمارات.

const demoLead = require('../src/lib/demo_lead');
check('`demo_lead` لسه بيفرض الرقم المصري (وده صح هناك)',
  demoLead.normalizePhone('+966512345678') === null
  && demoLead.normalizePhone('01552406406') === '01552406406',
  'الديمو للسوق المصري — القاعدة دي مقصودة.');
check('و`contact_validate` **مابيفرضهوش** (وده صح هنا)',
  cv.normalizePhone('+966512345678') === '+966512345678',
  'نموذج التواصل بيوصله أرقام خليجية بعد ما فتحنا السعودية والإمارات. '
  + 'توحيد الدالتين بيقفل السوق الجديد من غير ما حد يلاحظ.');

// ── ٥) والراوت بيستخدم التحقّق فعلاً ───────────────────────────────────

const src = read('src/routes/legal.js')
  .replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/^\s*\/\/.*$/gm, ' ');
check('`POST /contact` بينده التحقّق', /contactValidate\.validate\(/.test(src),
  'الموديول موجود بس الراوت مش بيستخدمه — يعني مفيش تحقّق فعلي.');
check('وبيحفظ القيم المنضّفة مش الخام', /v\.value\.name/.test(src) && /v\.value\.email/.test(src),
  'حفظ الخام معناه إن الرقم العربي بيتخزّن عربي والإيميل بحروف كبيرة.');
check('وتحويلات النموذج على المسار النهائي',
  !/redirect\('\/contact\?/.test(src),
  '`/contact` بقى بيتحوّل ٣٠١ على `/ar/contact` — فتحويل النموذج عليه '
  + 'بيعمل تحويلتين ورا بعض على كل إرسال.');

process.exit(failed ? 1 : 0);
