#!/usr/bin/env node
/**
 * برومبتات البوستات لازم تفضل مطابقة للكود.
 *
 * ── ليه ────────────────────────────────────────────────────────────────
 *
 * الملف ده بيتبعت لمانوس، ومانوس بيكتب منه بوستات بتتنشر **للعامة**.
 * يعني أي رقم غلط فيه بيوصل لعميل محتمل قبل ما حد يراجعه.
 *
 * وده مش افتراضي: صفحة الصيدلية وعدت بـ«تنبيهات صلاحية» والشاشة مكانتش
 * موجودة، والغلط اتكشف **وإحنا بنرد على عميل حقيقي**. الفرق الوحيد إن
 * البوست أوسع انتشاراً من الصفحة، وماينفعش يتسحب بعد ما يتشارك.
 *
 * الفحص ده بيربط الملف بالكود في تلات نقط بتتغيّر فعلاً: أسعار الأنظمة،
 * سلَجات الديمو، وروابط الصفحات (اللي اتغيّرت كلها في تقسيم اللغة).
 *
 * Usage: node scripts/check-social-prompts.js
 */
'use strict';
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');
const read = (p) => fs.readFileSync(path.join(ROOT, p), 'utf8');

let failed = 0;
const check = (label, ok, why) => {
  console.log((ok ? '✅ ' : '❌ ') + label + (ok ? '' : '\n   ' + why));
  if (!ok) failed += 1;
};

const DOC = 'docs/SOCIAL_POSTS_PROMPT.md';
const doc = read(DOC);

const { PRICES, FREE_MONTHS, arabicNumber } = require('../src/lib/pricing');
const { DEMO_SLUGS } = require('../src/lib/demo_mode');
const { SECTORS } = require('../src/lib/sector_landings');
const { SERVICES } = require('../src/lib/services');
const langRoutes = require('../src/lib/lang_routes');
const PUBLIC = langRoutes.publicPaths();

// ── ١) القاعدتين اللي المالك حدّدهم ────────────────────────────────────
//
// دول مش تفاصيل تحرير — دول سبب وجود الملف. لو اتشالوا بالغلط في تعديل،
// مانوس هينشر من غير ما يتأكد من الناشر ولا يرفق صورة.

/* القاعدة لازم تكون في **المكانين**: قسم القواعد فوق (اللي المالك بيقراه)
 * والبرومبت اللي بيتبعت لمانوس (اللي بينفّذ منه). لو فضلت في واحد بس،
 * نص الملف بيبقى ناقص القاعدة — وأول اختبار لده اتعمل بمسح جملة من قسم
 * القواعد، والفحص عدّى لأن نسخة البرومبت لسه موجودة. فبنعدّ. */
const publishRule = (doc.match(/افتح البوست وشوف الاسم/g) || []).length;
check('قاعدة «النشر من حساب وصفحة OscarDevs» في المكانين',
  /صفحة OscarDevs/.test(doc) && /مش من حساب شخصي/.test(doc) && publishRule >= 2,
  `خطوة التأكد بعد النشر مذكورة ${publishRule} مرة (المطلوب مرتين: في قسم `
  + 'القواعد وفي البرومبت). من غيرها، فيسبوك بيفتح الناشر على البروفايل '
  + 'الشخصي افتراضياً والبوست بيتنشر باسم المالك.');

check('قاعدة «صورة بتوضّح كلام البوست» موجودة',
  /صورة بتوضّح كلام البوست/.test(doc) && /لقطة/.test(doc)
  && /مش لوجو/.test(doc),
  'من غيرها بتتحط صورة عامة، والبوست بيفقد اللي بيثبت كلامه.');

check('ومنع الإيموشن موجود', /ممنوع.{0,12}☺️/.test(doc) || /ممنوع إيموشن/.test(doc),
  'قاعدة دائمة في `CLAUDE.md`.');

check('ومنع الوعد بأرقام موجود', /متوعدش برقم/.test(doc),
  '«هتزوّد مبيعاتك ٣٠٪» ادعاء مقسناهوش — وده بيكسر ثقة العميل من أول مكالمة.');

// ── ٢) كل سلَج ديمو مذكور موجود فعلاً ──────────────────────────────────
//
// سلَج غلط = مانوس بيفتح ٤٠٤ وبياخد الصورة من مكان تاني أو بيخترعها.

const slugs = [...doc.matchAll(/\*\*الديمو:\*\*\s*`([a-z]+)`(?:\s*·\s*`([a-z]+)`)?/g)]
  .flatMap((m) => [m[1], m[2]]).filter(Boolean);
check(`سلَجات الديمو المذكورة (${slugs.length}) كلها موجودة`,
  slugs.every((s) => DEMO_SLUGS.has(s)),
  'مش موجود: ' + slugs.filter((s) => !DEMO_SLUGS.has(s)).join('، '));
check('وفيه سلَج ديمو لكل منتج تقريباً', slugs.length >= 12,
  `لقيت ${slugs.length} بس — الصورة لازم تيجي من ديمو، فكل منتج محتاج سلَجه.`);

// ── ٣) كل سعر مذكور مطابق لـ`pricing.js` ───────────────────────────────
//
// السعر في البوست هو أول رقم العميل بيشوفه. اختلافه عن الصفحة بيخلّي
// أول مكالمة تبدأ بـ«إنتوا قلتوا كام؟».

const priced = [...doc.matchAll(/\*\*الصفحة:\*\*\s*`\/ar\/([a-z0-9-]+)`[^\n]*?\*\*([٠-٩]+)\s*ج\/شهر\*\*/g)];
/* صفحة ورش السيارات مش في `SECTORS` — هي صفحة مستقلة (`WORKSHOP_LANDING`)
 * اتكتبت قبل الحلقة القطاعية. سعرها بيتقرا من نفس `PRICES` بالمفتاح
 * `workshop`، فالاستثناء هنا في **مكان القراءة** مش في مصدر السعر. */
const LANDING_TYPE = { 'car-workshop-management-egypt': 'workshop' };
const typeOf = (slug) => (SECTORS[slug] ? SECTORS[slug].type : LANDING_TYPE[slug]);

const wrong = [];
for (const m of priced) {
  const type = typeOf(m[1]);
  if (!type || !PRICES[type]) { wrong.push(`${m[1]} — مش نظام معروف`); continue; }
  const real = arabicNumber(PRICES[type].monthly);
  if (real !== m[2]) wrong.push(`${m[1]}: الملف ${m[2]} والكود ${real}`);
}
check(`أسعار الأنظمة في الملف (${priced.length}) مطابقة للكود`, wrong.length === 0,
  wrong.join(' · '));
const expectPriced = Object.keys(SECTORS).length + Object.keys(LANDING_TYPE).length;
check('وفيه سعر مذكور لكل نظام ليه صفحة', priced.length === expectPriced,
  `الملف فيه ${priced.length} والمتوقّع ${expectPriced} — نظام بلا سعر في الملف `
  + 'معناه إن مانوس هيكتب بوست من غير ما يعرف يقول كام.');

check(`العرض المجاني ${arabicNumber(FREE_MONTHS)} شهور زي الكود`,
  new RegExp(`مجاني أول ${arabicNumber(FREE_MONTHS)} شهور`).test(doc),
  `الكود بيقول ${FREE_MONTHS} — لو اتغيّر، الملف لازم يتغيّر معاه.`);

// ── ٤) كل رابط صفحة في الملف بيوصل فعلاً ───────────────────────────────
//
// الروابط دي كلها اتغيّرت في تقسيم اللغة. الملف اللي فضل بيقول `/dental`
// كان هيدّي مانوس رابط بيتحوّل ٣٠١.

const links = [...doc.matchAll(/`(\/ar\/[a-z0-9/-]+)`/g)].map((m) => m[1]);
const dead = [...new Set(links)].filter((l) => !PUBLIC.has(l.replace(/^\/ar/, '') || '/'));
check(`روابط الصفحات في الملف (${new Set(links).size}) كلها موجودة`, dead.length === 0,
  'مش موجود: ' + dead.join('، '));
check('والروابط عليها prefix اللغة', !/`\/(?!ar\/)[a-z][a-z0-9-]*`\s*·\s*\*\*[٠-٩]/.test(doc),
  'رابط من غير `/ar/` بيتحوّل ٣٠١ — ومانوس ممكن ينشره زي ما هو.');

// ── ٥) وكل خدمة تطوير مذكورة، ومعاها الفرق بين خدمة ونظام ──────────────

for (const s of Object.keys(SERVICES)) {
  check(`خدمة ${s} مذكورة`, doc.includes('/ar/' + s), 'ناقصة من الملف.');
}
check('والملف بيقول إن الخدمات مش بتتزوّد على الـ١٢ نظام',
  /خدمة.{0,40}مش نظام جاهز/.test(doc) && /متجمّعهمش/.test(doc),
  'من غير الجملة دي هيطلع بوست بيقول «١٥ نظام» — ونفس غموض العدّ اللي '
  + 'اتصلّح في `llms.txt` بيرجع تاني، بس المرة دي في بوست منشور.');

// ── ٦) وتحذير الحضانة والتغذية موجود ───────────────────────────────────

check('تحذير «ممنوع صورة أو ذكر طفل حقيقي» في الحضانة',
  /ممنوع أي صورة أو ذكر لطفل حقيقي/.test(doc),
  'صور الأطفال خط أحمر — وبيانات الديمو هي المسموح بس.');
check('وتحذير «مفيش نصيحة طبية» في التغذية',
  /نصيحة طبية/.test(doc),
  'بوست تغذية فيه وعد بإنقاص وزن ادعاء صحي — وده ممنوع في سياسات أدسنس '
  + 'وفي `docs/NUTRITION_DOCTOR_ROADMAP.md`.');

process.exit(failed ? 1 : 0);
