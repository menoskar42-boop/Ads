// ===== الحكم على «كتب الحرف صح» =====
//
// اتفصل عن `trace.js` عشان يتقاس بره المتصفّح: الحارس
// (`scripts/check-trace-judge.js`) بينادي الدوال دي بنفسه بأرقام حقيقية،
// بدل ما يقرا الملف ويفترض إنه بيعمل اللي مكتوب فيه.
//
// ── الثغرة اللي الملف ده اتعمل عشانها ────────────────────────────────────
//
// الشرط القديم كان سطر واحد:
//
//     covered / maskTotal >= 0.62
//
// يعني «قد إيه من الحرف اتغطّى» — ومافيش أي قياس لـ«قد إيه من اللي الطفل
// رسمه وقع **بره** الحرف». فالطفل اللي بيشخبط على المربّع كله بفرشاة عريضة
// بيغطّي ١٠٠٪ من القناع، والتطبيق بيقول لأهله **«برافو! كتب الحرف صح»**.
//
// دي مش مكافأة زيادة — دي معلومة غلط بتوصل لأب بيتابع ابنه، وطفل بيتعلّم
// إن الشخبطة والكتابة نفس الحاجة.
'use strict';

export const THRESHOLD = 0.62;   // نسبة الحرف اللي لازم تتغطّى
export const PRECISION = 0.55;   // نسبة رسم الطفل اللي لازم تقع جوّه الحرف

/**
 * @param covered   بكسلات رسمها الطفل ووقعت جوّه الحرف
 * @param drawn     كل البكسلات اللي رسمها
 * @param maskTotal بكسلات الحرف نفسه
 *
 * @returns { coverage, precision, ok }
 *
 * ملحوظتين مقصودتين:
 *   · **صفر رسم = صفر دقّة**، مش «مية بالمية». القسمة على صفر لو اتسابت
 *     بترجع NaN، وNaN في أي مقارنة بترجع false — يعني الصح بالصدفة، ولحد
 *     ما حد يقلب المقارنة يبقى غلط. فالحالة متكتوبة صراحةً.
 *   · **قناع فاضي = مافيش حكم.** لو الحرف نفسه مارسمش (خط مش محمّل مثلاً)،
 *     كل بكسل بيبقى «بره»، وتقييم الطفل ساعتها كدب علينا إحنا مش عليه هو.
 */
export function judge(covered, drawn, maskTotal) {
  const c = Number(covered) || 0;
  const d = Number(drawn) || 0;
  const m = Number(maskTotal) || 0;
  const coverage = m > 0 ? c / m : 0;
  const precision = d > 0 ? c / d : 0;
  return {
    coverage,
    precision,
    ok: m > 0 && coverage >= THRESHOLD && precision >= PRECISION,
  };
}

/**
 * الجملة اللي تتقال للطفل بعد ما يرفع إيده ولسه ماخلّصش.
 *
 * تلات إجابات مش اتنين. قبل كده كان فيه «صح» وسكوت — والسكوت أسوأ إجابة:
 * الطفل رسم حاجة والتطبيق ماردّش. والأهم إن **اللي شخبط واللي لسه مكمّلش
 * كانوا بياخدوا نفس السكوت**، وهما محتاجين كلام مختلف تماماً: واحد يمسح
 * ويرجع على الخط، والتاني يكمّل.
 *
 * @returns نص، أو null لما مايكونش فيه حاجة تستاهل تتقال (رسم قليل أوي).
 */
export function hintFor(m) {
  if (!m || m.ok) return null;
  if (m.coverage >= THRESHOLD && m.precision < PRECISION) {
    return "شكلك خرج بره الحرف 🙂 دوس امسح وارسم على الخط الفاتح.";
  }
  if (m.coverage >= THRESHOLD * 0.5) {
    return "كمّل! لسه شوية على الخط الفاتح ✏️";
  }
  return null;
}
