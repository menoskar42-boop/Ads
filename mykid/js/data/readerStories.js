/** الكلمات من غير علامات الترقيم (للنطق والضغط على الكلمة) */
export const storyWords = (text) => String(text).split(/\s+/).map((w) => w.replace(/[.،!؟:,]/g, "")).filter(Boolean);
const TASHKEEL = /[ً-ْٰ]/g;
export const bareWord = (w) => String(w).replace(TASHKEEL, "");

/** الحروف اللى الكلمة محتاجاها (أشكال الألف حرف واحد · «ال» بتتحسب ألف ولام) */
export function lettersNeeded(word) {
  return [...new Set([...bareWord(word)].map((c) => (/[أإآا]/.test(c) ? "أ" : c)))];
}
