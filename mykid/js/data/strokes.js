// ===== ترتيب واتجاه الخطوط لكل حرف ورقم (لوحة الكتابة) =====
//
// المالك ٢٠٢٦-١٠-١٠: بنته ٤ سنين بتتعلّم تكتب. كل حرف هنا = قايمة خطوط بالترتيب، وكل خط
// = نقط بالترتيب اللى الصباع بيمشى بيه (أول نقطة = النقطة الخضرا). النقطة اللوحدها
// (زى نقط ب/ت) خط بنقطة واحدة = لمسة.
//
// الإحداثيات ٠–١٠٠ (مربع الكتابة)، y لتحت. الحروف العربية من اليمين للشمال وجسم الحرف
// قبل نقطه. الأرقام (العربى والإنجليزى) بتتكتب من فوق لتحت، والعدد من رقمين من الشمال
// لليمين زى ما بيتقرا.
//
// الأشكال اتراجعت بالعين على صفحة تجميع (Chromium) — أى تعديل هنا اتفرّج عليه تانى.

const r1 = (n) => Math.round(n * 10) / 10;

/** خط مستقيم بين نقط. */
const L = (...pts) => pts.map(([x, y]) => [x, y]);

/** قوس بيضاوى: الزاوية بالدرجات، ٩٠ = تحت (y لتحت)، ومن a0 لـa1 بالترتيب. */
function arc(cx, cy, rx, ry, a0, a1, n) {
  const steps = n || Math.max(8, Math.round(Math.abs(a1 - a0) / 8));
  const out = [];
  for (let i = 0; i <= steps; i++) {
    const a = ((a0 + (a1 - a0) * (i / steps)) * Math.PI) / 180;
    out.push([r1(cx + rx * Math.cos(a)), r1(cy + ry * Math.sin(a))]);
  }
  return out;
}

/** منحنى بيزييه تكعيبى. */
function bez(p0, p1, p2, p3, n = 16) {
  const out = [];
  for (let i = 0; i <= n; i++) {
    const t = i / n, u = 1 - t;
    out.push([
      r1(u * u * u * p0[0] + 3 * u * u * t * p1[0] + 3 * u * t * t * p2[0] + t * t * t * p3[0]),
      r1(u * u * u * p0[1] + 3 * u * u * t * p1[1] + 3 * u * t * t * p2[1] + t * t * t * p3[1]),
    ]);
  }
  return out;
}

/** وصل أجزاء خط واحد (من غير ما نكرّر نقطة الوصل). */
function cat(...parts) {
  const out = [];
  for (const p of parts) for (const q of p) {
    const last = out[out.length - 1];
    if (!last || Math.hypot(last[0] - q[0], last[1] - q[1]) > 0.01) out.push(q);
  }
  return out;
}

