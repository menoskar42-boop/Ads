/** رقم من أكتر من خانة (١٠–٢٠): كل خانة متصغّرة جنب التانية، من الشمال لليمين. */
function compose(digits, table) {
  const n = digits.length;
  const s = n === 1 ? 1 : 0.62;
  const centers = n === 1 ? [50] : [29, 71];
  const out = [];
  for (let i = 0; i < n; i++) {
    const strokes = table[digits[i]];
    if (!strokes) return null;
    for (const st of strokes) out.push(st.map(([x, y]) => [r1(centers[i] + (x - 50) * s), r1(50 + (y - 50) * s)]));
  }
  return out;
}

/**
 * خطوط الحرف/الرقم ده — أو null لو مالوش (اللوحة بترجع للطريقة القديمة: «غطّى الحرف»).
 * `glyph` زى ما فى الداتا: "ب" · "B" · "٧" · "١٥" · "7" · "10".
 */
export function strokesFor(glyph) {
  if (!glyph) return null;
  if (AR[glyph]) return AR[glyph];
  if (EN[glyph]) return EN[glyph];
  if (/^[0-9]+$/.test(glyph)) return compose(glyph.split(""), DIGITS_EN);
  if (/^[٠-٩]+$/.test(glyph)) return compose(glyph.split(""), DIGITS_AR);
  return null;
}

