export const BREAK_EVERY_DEFAULT = 15;
export const BREAK_OPTIONS = [0, 10, 15, 20];
export const ENGLISH_ONLY_LEVEL = 3;

/** المهمة: [النص، اللى ميزو بيقوله] — بالدور باليوم ورقم الفاصل */
export function breakMission({ n = 0, color = null, letter = null } = {}) {
  const list = [
    ["قوم نط ٥ نطات وعدّهم بصوت عالى! 🦘", "يلا نقوم نط خمس نطات ونعدّهم سوا!"],
    ["لف حوالين نفسك مرتين ودوّر على حاجة بتحبها فى الأوضة 🌀", "لف حوالين نفسك مرتين!"],
    ["اشرب بُق مية واغسل وشك 💧", "يلا نشرب مية!"],
    ["مدّ إيدك لفوق خالص ولتحت خالص ٣ مرات 🙆", "مدّ إيدك لفوق ولتحت!"],
  ];
  if (color) list.unshift([`Bring something ${color.en}! هات حاجة لونها ${color.name} من البيت 🎨`, `Bring something ${color.en}!`]);
  if (letter) list.push([`ارسم حرف ${letter} فى الهوا بصباعك كبير ٣ مرات ✍️`, `ارسم حرف ${letter} فى الهوا بصباعك!`]);
  return list[n % list.length];
}

/** ترتيب النطق بعد الإجابة الصح: إنجليزى الأول، والعربى يتشال لو الطفل عارف اللون كويس */
export function confirmLangs({ en, mastery = 0 }) {
  if (!en) return ["ar", "en"];
  return mastery >= ENGLISH_ONLY_LEVEL ? ["en"] : ["en", "ar"];
}
